package com.example.localai.data.mock

import com.example.localai.data.model.ChatMessage
import com.example.localai.data.model.ChatRole
import com.example.localai.data.model.Conversation

/** Deterministic, canned chat content. No model is ever called. */
object MockChatRepository {

    private val codeKeywords = listOf("code", "function", "kotlin", "python", "bug", "compose", "script")

    private val generalReplies = listOf(
        "This is a simulated reply. In a future version, a locally running model would answer here.",
        "Demo response: I can't actually reason about your message yet, but this is how a reply would appear.",
        "Thanks for the message. Real on-device inference isn't connected in this build, so this text is pre-written."
    )

    private const val CODE_REPLY = "Here is a sample snippet (simulated, not generated by a model):\n\n" +
        "```kotlin\n" +
        "fun greet(name: String): String {\n" +
        "    return \"Hello, \$name!\"\n" +
        "}\n" +
        "```\n\n" +
        "A real model would tailor code like this to your request."

    /** A short seeded conversation shown when a chat is first opened. */
    fun seedConversation(startId: Long): List<ChatMessage> = listOf(
        ChatMessage(startId, ChatRole.USER, "What can you help me with?"),
        ChatMessage(
            startId + 1, ChatRole.ASSISTANT,
            "This is a demo conversation. Replies are pre-written to show the chat layout; " +
                "no model is loaded or running."
        ),
        ChatMessage(startId + 2, ChatRole.USER, "Show me a small Kotlin example."),
        ChatMessage(startId + 3, ChatRole.ASSISTANT, CODE_REPLY)
    )

    /** Sample history for the conversation drawer. The first entry starts active. */
    fun sampleConversations(): List<Conversation> = listOf(
        Conversation("c-1", "Getting started", "qwen-small-text", seedConversation(1)),
        Conversation(
            "c-2", "Kotlin coroutines help", "coder-small",
            listOf(
                ChatMessage(11, ChatRole.USER, "How do I run two coroutines in parallel?"),
                ChatMessage(
                    12, ChatRole.ASSISTANT,
                    "Demo response: launch each coroutine inside a coroutineScope, then wait for both."
                )
            )
        ),
        Conversation(
            "c-3", "Weekend trip ideas", "gemma-compact-text",
            listOf(
                ChatMessage(21, ChatRole.USER, "Give me three ideas for a weekend trip."),
                ChatMessage(
                    22, ChatRole.ASSISTANT,
                    "Demo response: a coastal walk, a mountain village, or a city food tour."
                )
            )
        ),
        Conversation(
            "c-4", "Meeting notes summary", "qwen-small-text",
            listOf(
                ChatMessage(31, ChatRole.USER, "Summarise these meeting notes.", listOf("notes.pdf")),
                ChatMessage(
                    32, ChatRole.ASSISTANT,
                    "Demo response: this is where a short summary of the attached notes would appear."
                )
            )
        )
    )

    /** Picks a reply based only on the prompt text and how many replies were already given. */
    fun replyFor(prompt: String, assistantRepliesSoFar: Int): String {
        val lower = prompt.lowercase()
        return if (codeKeywords.any { it in lower }) {
            CODE_REPLY
        } else {
            generalReplies[assistantRepliesSoFar % generalReplies.size]
        }
    }
}
